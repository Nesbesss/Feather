// Standalone package/integration smoke tests. These do not emulate WebKit or prove ad prevention.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import zlib from 'node:zlib';

const resource = new URL('../../../Feather/Resources/YouTube/upstream/', import.meta.url);
const bytes = readFileSync(new URL('youtube-upstream.js', resource));
const script = bytes.toString();
const manifest = JSON.parse(readFileSync(new URL('manifest.json', resource)));
let passed = 0;
const check = (name, run) => {run(); passed++; console.log('PASS ' + name);};

function realm(host = 'youtube.com') {
  const logs = [];
  class RealmResponse extends Response {}
  const context = vm.createContext({URL, Request, Response: RealmResponse, Headers,
    console: {log: value => logs.push(String(value).slice(0, 160))},
    location: {hostname: host, pathname: '/watch', href: `https://${host}/watch?v=synthetic01`}});
  // Do not alias window to a Node contextified global: Node's global proxy drops
  // existing accessors when defineProperty supplies only {configurable: true}.
  vm.runInContext(`
    class Window {}; globalThis.Window = Window;
    const document = {location, currentScript: null}; globalThis.document = document;
    class XMLHttpRequest {open(){} send(){} addEventListener(){}};
    globalThis.XMLHttpRequest = XMLHttpRequest;
    const nativeFetch = async () => new Response('{}'); globalThis.fetch = nativeFetch;
    globalThis.window = {JSON, location, document, fetch: nativeFetch, XMLHttpRequest,
      Response, Request, Headers, Promise, Window, Object, Array, Reflect, Proxy,
      WeakMap, Map, Set, RegExp, Function};
    globalThis.self = window;
  `, context);
  const run = code => vm.runInContext(code, context);
  run(script);
  return {context, run, logs};
}

check('manifest identifies the generated bytes', () => {
  assert.equal(createHash('sha256').update(bytes).digest('hex'), manifest.bundleSHA256);
});
check('lookalike domain does not install', () => {
  assert.equal(realm('youtube.com.example.org').run('globalThis.__featherYouTubeUpstream'), undefined);
});
check('canonical trailing-dot hosts select the same upstream rules', () => {
  const ordinary = realm().run('__featherYouTubeUpstream.eligibleRules');
  const canonical = realm('youtube.com.').run('__featherYouTubeUpstream.eligibleRules');
  assert.equal(canonical, ordinary);
  assert.equal(realm('YOUTUBE.COM.').run('__featherYouTubeUpstream.eligibleRules'), ordinary);
  assert.equal(realm('youtube.com.example.org.').run('globalThis.__featherYouTubeUpstream'), undefined);
});
check('all three initial ad fields are trapped', () => {
  const {run, logs} = realm();
  assert.equal(run(`window.ytInitialPlayerResponse={adPlacements:[1],adSlots:[2],playerAds:[3]};
    [window.ytInitialPlayerResponse.adPlacements,window.ytInitialPlayerResponse.adSlots,window.ytInitialPlayerResponse.playerAds].every(value=>value===undefined)`), true);
  assert.deepEqual(logs, []);
});
check('later nested writes stay trapped', () => {
  const {run} = realm();
  assert.equal(run(`window.ytInitialPlayerResponse={};window.ytInitialPlayerResponse.adPlacements=[1];
    window.ytInitialPlayerResponse.adSlots=[2];window.ytInitialPlayerResponse.playerAds=[3];
    [window.ytInitialPlayerResponse.adPlacements,window.ytInitialPlayerResponse.adSlots,window.ytInitialPlayerResponse.playerAds].every(value=>value===undefined)`), true);
});
check('modern Shorts array-pruning syntax is supported', () => {
  const {run} = realm();
  assert.equal(run(`JSON.parse('{"entries":[{"command":{"reelWatchEndpoint":{"adClientParams":{"isAd":true}}}},{"command":{"reelWatchEndpoint":{"videoId":"synthetic01"}}}]}').entries.length`), 1);
});
check('SABR envelope pruning preserves transport metadata', () => {
  const {run} = realm();
  assert.equal(run(`const value=JSON.parse('{"playerResponse":{"streamingData":{"serverAbrStreamingUrl":"synthetic"},"adPlacements":[1],"adSlots":[2]}}').playerResponse;
    !('adPlacements' in value)&&!('adSlots' in value)&&value.streamingData.serverAbrStreamingUrl==='synthetic'`), true);
});
check('DRM license route is excluded from upstream XHR matcher', () => {
  const rule = manifest.rules.find(rule => rule.name === 'json-prune-xhr-response');
  const argument = rule.args.at(-1);
  const regex = new RegExp(argument.slice(1, -1));
  assert.equal(regex.test('https://www.youtube.com/youtubei/v1/player?key=synthetic'), true);
  assert.equal(regex.test('https://www.youtube.com/youtubei/v1/player/get_drm_license?key=synthetic'), false);
});
check('diagnostic getter is immutable and reinjection is idempotent', () => {
  const {run} = realm();
  const before = run('__featherYouTubeUpstream.invokedRules');
  run(script);
  assert.equal(run('__featherYouTubeUpstream.invokedRules'), before);
  assert.equal(run('Object.getOwnPropertyDescriptor(globalThis,"__featherYouTubeUpstream").configurable'), false);
});

// Exercise the JSONPath rule directly with the same vendored function and args;
// the full www site-JS suite needs real DOM/player/network fixtures in WebKit.
check('vendored JSONPath conditional rule supports current mute-on-start fix', () => {
  const tar = zlib.gunzipSync(readFileSync(new URL('vendor/scriptlets-2.5.1.tgz', import.meta.url)));
  let offset = 0, json;
  while (offset + 512 <= tar.length) {
    const name = tar.subarray(offset, offset + 100).toString().split('\0')[0];
    const size = Number.parseInt(tar.subarray(offset + 124, offset + 136).toString().replace(/\0.*$/, '').trim(), 8) || 0;
    if (name === 'package/dist/scriptlets.corelibs.json') {json = JSON.parse(tar.subarray(offset + 512, offset + 512 + size)); break;}
    offset += 512 + Math.ceil(size / 512) * 512;
  }
  assert.ok(json);
  const rule = manifest.rules.find(rule => rule.line === 1051);
  const fn = json.scriptlets.find(item => item.names.includes(rule.name)).scriptlet;
  const {context, run, logs} = realm('example.org');
  context.args = rule.args;
  run(`(${fn})({name:'json-prune',uniqueId:'Feather-smoke-jsonpath',version:'2.5.1',engine:'corelibs',verbose:false},args)`);
  assert.equal(run(`const value=JSON.parse('{"playerResponse":{"cards":{},"playabilityStatus":{},"playerConfig":{"audioConfig":{"muteOnStart":true,"keep":1}}}}');
    !('muteOnStart' in value.playerResponse.playerConfig.audioConfig)&&value.playerResponse.playerConfig.audioConfig.keep===1`), true);
  assert.deepEqual(logs, []);
});
console.log(JSON.stringify({suite: 'upstream-node-smoke', passed, limitation: 'Not WebKit behavior or live YouTube efficacy.'}));
